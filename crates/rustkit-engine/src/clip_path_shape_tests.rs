/// The renderer's outline mask takes 4 samples a pixel (5 coverage levels;
/// Skia's analytic coverage has 256). This pin measures the error on every
/// edge pixel of a diagonal instead of leaving it between the sampled rows.
/// Measured when it was added: worst 1 channel value, mean 1.0, over all
/// 400 edge pixels. Chromium's clip edges on this polygon land on the same
/// quarter steps the 4 standard sample positions give. The tolerance is that
/// worst case, so the error can only get smaller.
const DIAGONAL_EDGE_TOLERANCE: u8 = 1;

#[test]
fn a_diagonal_edge_is_antialiased_within_a_stated_error_of_chromium() {
    let f = frame(TRIANGLE_PAGE);
    let mut worst = (0u8, 0u32, 0u32);
    let mut total = 0u64;
    for &(x, y, want) in TRIANGLE_EDGE {
        let px = f[(y * W + x) as usize];
        let off = px.iter().zip(want).map(|(g, w)| g.abs_diff(w)).max().unwrap();
        total += off as u64;
        if off > worst.0 {
            worst = (off, x, y);
        }
    }
    eprintln!(
        "C8B_EDGE_AA {} edge pixels: worst {} at ({},{}), mean {:.1}",
        TRIANGLE_EDGE.len(),
        worst.0,
        worst.1,
        worst.2,
        total as f64 / TRIANGLE_EDGE.len() as f64
    );
    assert!(
        worst.0 <= DIAGONAL_EDGE_TOLERANCE,
        "edge pixel ({},{}) off Chromium by {} (stated tolerance {})",
        worst.1,
        worst.2,
        worst.0,
        DIAGONAL_EDGE_TOLERANCE
    );
}

const CIRCLE_OVER_BOX_PAGE: &str = r#"<!DOCTYPE html><html><body style="margin:0;background:#fff"><div id="under" style="position:absolute;left:50px;top:50px;width:200px;height:200px;background:#ccc"></div><div id="c" style="position:absolute;left:50px;top:50px;width:200px;height:200px;background:#00f;clip-path:circle(50%)"></div></body></html>"#;

/// Hit testing honours every clip-path shape, not only C8b's outlines
/// (#1052's review, nit 3): a click in a `circle()` box's corner, outside
/// the circle, reaches the element underneath. Chrome for Testing
/// 148.0.7778.216 on this page: the four corners hit `under`, the centre
/// and the top middle hit `c`.
#[test]
fn a_click_in_a_circle_corner_falls_through_to_the_element_underneath() {
    let mut engine = Engine::new(EngineConfig::default()).expect("engine");
    let view = engine
        .create_headless_view(Bounds { x: 0, y: 0, width: W, height: H })
        .expect("view");
    engine.load_html(view, CIRCLE_OVER_BOX_PAGE).expect("load_html");
    let got = engine
        .execute_script(
            view,
            "[[55,55],[245,55],[55,245],[245,245],[150,150],[150,55]].map(function (p) { \
             var e = document.elementFromPoint(p[0], p[1]); return e ? (e.id || e.tagName) : 'none'; }).join(' ')",
        )
        .expect("script");
    let got = got.strip_prefix("String(\"").and_then(|v| v.strip_suffix("\")")).unwrap_or(&got);
    assert_eq!(got, "under under under under c c");
}

/// An unparsable `path()` makes the whole declaration invalid, so the box
/// is not clipped at all (#1052's review, nit 5). Chrome for Testing
/// 148.0.7778.216 drops every one of these at parse time (the inline style
/// reads empty, `getComputedStyle` reads `none`) and paints the whole box,
/// `path('')` included: an empty path string is not a valid path there.
#[test]
fn an_invalid_path_leaves_the_box_unclipped() {
    let blue = [0, 0, 255];
    for path in [
        "path('garbage')",
        "path('')",
        "path('M 0 0 L 10')",
        "path('M 0 0 L 100 0 L 0 100 Z garbage')",
        "path(evenodd, 'zz')",
    ] {
        let page = format!(
            "<!DOCTYPE html><html><body style=\"margin:0;background:#fff\"><div style=\"position:absolute;left:50px;top:50px;\
             width:200px;height:200px;background:#00f;clip-path:{path}\"></div></body></html>"
        );
        let f = frame(&page);
        assert_eq!(f[(240 * W + 240) as usize], blue, "{path}: (240,240) is inside the unclipped box");
        assert_eq!(f[(60 * W + 60) as usize], blue, "{path}: (60,60) is inside the unclipped box");
    }
    // A valid path still clips (control).
    let f = frame(
        "<!DOCTYPE html><html><body style=\"margin:0;background:#fff\"><div style=\"position:absolute;left:50px;top:50px;\
         width:200px;height:200px;background:#00f;clip-path:path('M 0 0 L 100 0 L 0 100 Z')\"></div></body></html>",
    );
    assert_eq!(f[(240 * W + 240) as usize], WHITE, "a valid path clips (240,240) away");
}
