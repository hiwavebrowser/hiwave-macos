/// The display list carries the shape, not its bounding box: one
/// `PushClipPath` with the outline in page px and the fill rule, closed by
/// the `PopClip` every clip uses.
#[test]
fn the_display_list_carries_the_outline_and_fill_rule() {
    let list = |page: &str| -> Vec<String> {
        let mut engine = Engine::new(EngineConfig::default()).expect("engine");
        let view = engine
            .create_headless_view(Bounds { x: 0, y: 0, width: W, height: H })
            .expect("view");
        engine.load_html(view, page).expect("load_html");
        let list = engine.views[&view].display_list.clone().expect("display list");
        list.commands.iter().map(|c| format!("{c:?}")).collect()
    };
    let lines = list(TRIANGLE_PAGE);
    let all = lines.join("\n");
    let clip = lines
        .iter()
        .find(|c| c.starts_with("PushClipPath"))
        .unwrap_or_else(|| panic!("no PushClipPath:\n{all}"));
    assert!(clip.contains("[(150.0, 50.0), (250.0, 250.0), (50.0, 250.0)]"), "{clip}");
    assert!(clip.contains("even_odd: false"), "{clip}");
    assert!(!lines.iter().any(|c| c.starts_with("PushClip(")), "no bounding-box clip as well:\n{all}");

    let lines = list(STAR_EVENODD_PAGE);
    let clip = lines.iter().find(|c| c.starts_with("PushClipPath")).expect("star clip");
    assert!(clip.contains("even_odd: true"), "{clip}");

    for page in [PATH_CURVES_PAGE, SHAPE_FUNC_PAGE] {
        let lines = list(page);
        assert!(
            lines.iter().any(|c| c.starts_with("PushClipPath")),
            "{}",
            lines.join("\n")
        );
    }
}
