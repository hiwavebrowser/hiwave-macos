/// The view's frame, row-major RGB.
fn frame(html: &str) -> Vec<[u8; 3]> {
    let mut engine = Engine::new(EngineConfig::default()).expect("engine");
    let view = engine
        .create_headless_view(Bounds { x: 0, y: 0, width: W, height: H })
        .expect("view");
    engine.load_html(view, html).expect("load_html");
    capture(&mut engine, view)
}

fn capture(engine: &mut Engine, view: EngineViewId) -> Vec<[u8; 3]> {
    let viewhost_id = engine.views[&view].viewhost_id;
    let list = engine.views[&view].display_list.clone().expect("display list");
    let path = std::env::temp_dir().join(format!(
        "rustkit-clip-path-shape-{}-{:?}.ppm",
        std::process::id(),
        std::thread::current().id()
    ));
    engine
        .presenter
        .as_mut()
        .expect("presenter")
        .draw_scrolled(viewhost_id, &list, (0.0, 0.0), Some(path.to_str().unwrap()))
        .expect("capture");
    let ppm = std::fs::read(&path).expect("frame");
    let _ = std::fs::remove_file(&path);
    let pixels = (W * H) as usize;
    assert!(ppm.len() >= pixels * 3, "a {W}x{H} frame");
    ppm[ppm.len() - pixels * 3..]
        .chunks(3)
        .map(|p| [p[0], p[1], p[2]])
        .collect()
}

/// Compare `got` with Chromium's rows: flat runs (two pixels or more, or a
/// run in one of the page's flat colours) to 2 levels, edge pixels to 64.
fn assert_rows(got: &[[u8; 3]], rows: Rows, flat: &[[u8; 3]], what: &str) {
    let mut misses = Vec::new();
    for &(y, runs) in rows {
        for &(x0, x1, want) in runs {
            let edge = x1 - x0 == 1 && !flat.contains(&want);
            let tol = if edge { 64 } else { 2 };
            for x in x0..x1 {
                let px = got[(y * W + x) as usize];
                let off = px.iter().zip(want).map(|(g, w)| g.abs_diff(w)).max().unwrap();
                if off > tol {
                    misses.push(format!("({x},{y}) got {px:?} Chromium {want:?} ±{tol}"));
                }
            }
        }
    }
    assert!(
        misses.is_empty(),
        "{what}: {} pixels off Chromium, first: {:#?}",
        misses.len(),
        &misses[..misses.len().min(12)]
    );
}

